# Builds Source/PresetGains.h from a QC CSV so every preset lands near its category's target loudness.
import csv, math, sys
target = {"Classic": None, "808": -12.5, "Bass": -11.5, "Lead": -15.5, "Pluck": -16.5, "Keys": -16.0, "Pad": -16.0, "FX": -17.0, "Piano": -15.5, "Chords": -15.5, "Strings": -16.0, "Brass": -15.0, "Choir": -16.0, "Cinematic": -14.0, "Ambient": -17.0, "Multi": -14.0}
rows = list(csv.reader(open(sys.argv[1])))
old = {}
if len(sys.argv) > 2:  # previous gains, to refine iteratively
    for i, line in enumerate(open(sys.argv[2]).read().split("{",1)[1].split("}")[0].split(",")):
        line=line.strip().rstrip("f")
        if line: old[i] = float(line)
n = max([int(r[0]) for r in rows] + [max(old.keys(), default=-1)]) + 1
gains = [old.get(i, 0.0) for i in range(n)]
for r in rows:   # only presets measured in this CSV are adjusted; the rest keep their old gain
    i, cat, rms = int(r[0]), r[1], float(r[5])
    if target[cat] is not None:
        g = gains[i] + max(-12.0, min(12.0, target[cat] - 20 * math.log10(max(rms, 1e-6)))) * 0.85
        gains[i] = max(-18.0, min(18.0, g))
with open("Source/PresetGains.h", "w") as f:
    f.write("#pragma once\n// Loudness-match offsets in dB, one per preset. Generated by Tools/make_gains.py from a QC render.\n")
    f.write(f"static constexpr int kPresetGainCount = {len(gains)};\n")
    f.write("static constexpr float kPresetGainDb[] = {" + ",".join(f"{g:.2f}f" for g in gains) + "};\n")
print("wrote", len(gains), "gains; range", round(min(gains),1), "to", round(max(gains),1), "dB")
